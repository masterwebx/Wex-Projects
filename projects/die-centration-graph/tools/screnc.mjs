const ESCAPE_ENCODE = {
  '\r': '@#',
  '\n': '@&',
  '<': '@!',
  '>': '@*',
  '@': '@$'
};

function isTransformableByte(byte) {
  return byte === 0x09
    || (byte > 0x1f && byte < 0x80 && byte !== 0x3c && byte !== 0x3e && byte !== 0x40);
}

function buildEncodeMap() {
  const map = [{}, {}, {}];
  for (let plain = 31; plain <= 127; plain++) {
    const plainByte = plain === 31 ? 0x09 : plain;
    if (!isTransformableByte(plainByte)) continue;
    const offset = (plain - 31) * 3;
    for (let p = 0; p < 3; p++) map[p][plainByte] = RAW_DATA[offset + p];
  }
  return map;
}

const encodeMap = buildEncodeMap();

function encodeUInt32LE(value) {
  const buf = Buffer.alloc(4);
  buf.writeUInt32LE(value >>> 0, 0);
  return buf.toString('base64');
}

function escapeEncodedByte(byte) {
  const ch = String.fromCharCode(byte);
  return Object.prototype.hasOwnProperty.call(ESCAPE_ENCODE, ch) ? ESCAPE_ENCODE[ch] : ch;
}

function isUtf8ContinuationByte(byte) {
  return (byte & 0xc0) === 0x80;
}

/** Encode plain script source to a #@~^...^#~@ block. */
export function encodeScript(plain) {
  const buf = Buffer.from(String(plain), 'utf8');
  let body = '';
  let checksum = 0;
  let index = 0;
  let encodedUnits = 0;

  for (let i = 0; i < buf.length; i++) {
    const byte = buf[i];
    if (byte < 0x80) {
      checksum = (checksum + byte) >>> 0;
      const pick = PICK[index % 64];
      const encodedByte = encodeMap[pick][byte] != null ? encodeMap[pick][byte] : byte;
      const piece = escapeEncodedByte(encodedByte);
      body += piece;
      encodedUnits += piece.length;
      index += 1;
      continue;
    }
    body += String.fromCharCode(byte);
    if (!isUtf8ContinuationByte(byte)) encodedUnits += 1;
  }

  return START_MARKER + encodeUInt32LE(encodedUnits) + body + encodeUInt32LE(checksum) + END_MARKER;
}

export default { encodeScript };
